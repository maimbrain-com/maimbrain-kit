            assert!(cargo.contains(SDK_GIT) && !cargo.contains("path = \"../") && cargo.contains("[workspace]"), "{}: {cargo}", k.name);
            assert!(dir.join("icon.png").is_file() && dir.join("src/lib.rs").is_file() && dir.join("DESIGN.md").is_file(), "{}", k.name);
            assert!(!dir.join("kit.toml").exists());
            for (path, _) in k.files {
                if is_text(path) {
                    let text = std::fs::read_to_string(dir.join(path)).unwrap();
                    assert!(!text.contains(&k.crate_name()), "{}: {path} still names {}", k.name, k.crate_name());
                }
            }
            assert!(dir.join("tools/sfx.py").is_file() && dir.join("tools/pixel.py").is_file() && dir.join("tools/check_audio.py").is_file(), "{}", k.name);
